# Writes proxy/vk_features.h: every VkPhysicalDevice*Features* struct of third_party/vulkan's vulkan_core.h whose members
# after sType and pNext are all VkBool32, by its sType, so the Vulkan recorder layer can write a device's enabled features.
#   python proxy/vk_features.py
# VkPhysicalDeviceFeatures2 (its features member) is the layer's own case. A struct whose sType doesn't match its name is
# left out: the layer writes it as unknown.
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, 'third_party', 'vulkan', 'vulkan', 'vulkan_core.h'), encoding='utf-8').read()
core = re.sub(r'#ifdef VK_ENABLE_BETA_EXTENSIONS\n.*?#endif', '', src, flags=re.S)  # vulkan_beta.h's, not built here
stypes = set(re.findall(r'^\s+(VK_STRUCTURE_TYPE_\w+) = ', core, re.M))


# matched without underscores: VkPhysicalDeviceVulkan11Features is VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_1_FEATURES
by_flat = {t[len('VK_STRUCTURE_TYPE_'):].replace('_', ''): t for t in stypes}


rows, skipped = [], []
for name, members in re.findall(r'^typedef struct (VkPhysicalDevice\w*Features\w*) \{\n(.*?)\n\} \1;', src, re.M | re.S):
    fields = [m.strip().rstrip(';').split() for m in members.split('\n') if m.strip()]
    if len(fields) < 3 or fields[0] != ['VkStructureType', 'sType'] or fields[1][-1] != 'pNext':
        continue
    if any(f[0] != 'VkBool32' for f in fields[2:]):
        skipped.append(name)
        continue
    st = by_flat.get(name[2:].upper())
    if st is None:
        skipped.append(name)
        continue
    rows.append((st, name, fields[2][1], fields[-1][1], len(fields) - 2))

with open(os.path.join(HERE, 'vk_features.h'), 'w', newline='\n') as f:
    f.write('// Generated by proxy/vk_features.py from third_party/vulkan/vulkan/vulkan_core.h. Do not edit.\n')
    f.write('#pragma once\n#include <cstddef>\n\n')
    f.write('// A feature struct by its sType: how many VkBool32 members follow its header (never its tail padding).\n')
    f.write('static const struct {\n    VkStructureType type;\n    uint32_t bools;\n} kVkFeatureStructs[] = {\n')
    for st, name, first, last, n in rows:
        f.write(f'    {{{st}, {n}}},\n')
    f.write('};\n\n')
    for st, name, first, last, n in rows:  # contiguous VkBool32 right after the 16-byte header
        f.write(f'static_assert(offsetof({name}, {first}) == 16 && offsetof({name}, {last}) == 16 + {n - 1} * sizeof(VkBool32));\n')
print(len(rows), 'structs;', len(skipped), 'left out:', ' '.join(skipped))
